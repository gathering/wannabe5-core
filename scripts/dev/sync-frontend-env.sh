#!/usr/bin/env bash
# Write wannabe5-frontend/.env.local pointing at core (+ shared AUTH_PUBLIC_KEY).
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
FRONTEND_ROOT="${FRONTEND_ROOT:-$ROOT/../wannabe5-frontend}"
# Loopback for Next SSR/proxy → core. Browser login redirects use FRONTEND_URL.
CORE_URL="${CORE_URL:-http://127.0.0.1:8000}"
FRONTEND_URL="${FRONTEND_URL:-http://wannabe5.gathering.org:3000}"

if [[ ! -d "$FRONTEND_ROOT" ]]; then
  echo "Frontend repo not found at $FRONTEND_ROOT (set FRONTEND_ROOT)" >&2
  exit 1
fi

python3 -c "
from pathlib import Path
import json, re
root = Path(r'''$ROOT''')
frontend = Path(r'''$FRONTEND_ROOT''')
core_url = r'''$CORE_URL'''
frontend_url = r'''$FRONTEND_URL'''
text = (root / 'env/local-stack.env').read_text()
m = re.search(r'AUTH_USER_PUBLIC_KEY=\"([^\"]+)\"', text)
if not m:
    raise SystemExit('AUTH_USER_PUBLIC_KEY missing/malformed in env/local-stack.env')
pem = m.group(1).encode().decode('unicode_escape')
auth_public = json.dumps({'key': pem})
# Browser uses relative /api (Next rewrite). SSR uses API_INTERNAL_URL to reach core.
(frontend / '.env.local').write_text(
    '# Generated by wannabe5-core make frontend-env — points frontend at core.\\n'
    f'BASE_URL={frontend_url}\\n'
    'API_URL=/api\\n'
    f'API_INTERNAL_URL={core_url}/api\\n'
    f'API_PROXY_DESTINATION={core_url}/api\\n'
    f\"AUTH_PUBLIC_KEY='{auth_public}'\\n\"
)
print(f'Wrote {frontend / \".env.local\"}')
print(f'BASE_URL={frontend_url} (open the app here, not localhost)')
print('Login: /api/auth/login → Keycloak → callback on wannabe5.gathering.org:8000')
"
